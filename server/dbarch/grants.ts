import { ident } from "./readonly.js";
import { SENSITIVE_RE } from "./permissions.js";
import type { CheckDef } from "./types.js";

export const MONITOR_ROLE = "secval_monitor";
const SENSITIVE = new RegExp(SENSITIVE_RE, "i");

export interface RequiredGrants {
  /** "table.column" pairs secval's checks must read. Key columns only. */
  columns: string[];
  /** Key columns that look personal/secret: NOT granted automatically, need a human decision. */
  skipped: string[];
}

/** Which columns the approved checks (and the migration ledger version) need. Nothing else is ever requested. */
export function requiredGrants(defs: CheckDef[], ledger: { table: string; column: string } | null): RequiredGrants {
  const all = new Set<string>();
  for (const d of defs) { all.add(`${d.child.table}.${d.child.column}`); all.add(`${d.parent.table}.${d.parent.column}`); }
  if (ledger) all.add(`${ledger.table}.${ledger.column}`);
  const columns: string[] = [], skipped: string[] = [];
  for (const k of [...all].sort()) (SENSITIVE.test(k.split(".")[1]!) ? skipped : columns).push(k);
  return { columns, skipped };
}

/**
 * The exact column-level GRANT script for the owner to review and run. SELECT on
 * named columns only; no table-wide or future-table privilege. New tables stay
 * unreadable until this is regenerated and run again.
 */
export function grantsSql(g: RequiredGrants, generatedAt: string): string {
  const byTable = new Map<string, string[]>();
  for (const k of g.columns) { const [t, c] = k.split("."); byTable.set(t!, [...(byTable.get(t!) ?? []), c!]); }
  const lines = [
    `-- Generated by secval on ${generatedAt}. Review, then run as the table-owner role in the Neon SQL Editor.`,
    `-- Grants SELECT on ${g.columns.length} key column(s) only. No table-wide and no future-table privileges.`,
  ];
  for (const [t, cols] of byTable) lines.push(`GRANT SELECT (${cols.map(ident).join(", ")}) ON ${ident(t)} TO ${MONITOR_ROLE};`);
  if (g.skipped.length) lines.push(`-- NOT granted (name looks personal or secret, needs your decision): ${g.skipped.join(", ")}`);
  return lines.join("\n") + "\n";
}
